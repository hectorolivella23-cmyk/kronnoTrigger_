//Agrega un boton por cada actividad del dia (los mismos botones de color del calendario)
private void llenarLista(ArrayList<Actividad> actividades){
    listaEventos.removeAll();
    for(Actividad actividad : actividades){
        javax.swing.JButton btnEvento = calendario.crearBotonEvento(actividad);
        btnEvento.setMaximumSize(new java.awt.Dimension(Integer.MAX_VALUE, 26));
        btnEvento.addActionListener(new java.awt.event.ActionListener() {
            public void actionPerformed(java.awt.event.ActionEvent evt) {
                //Al abrir un evento se cierra esta ventana
                EventosDelDia.this.dispose();
            }
        });
        listaEventos.add(btnEvento);
        listaEventos.add(javax.swing.Box.createVerticalStrut(4));
    }
    listaEventos.revalidate();
    listaEventos.repaint();
}

