package modelo;

public class HorarioRecurrente {

    private String dia;
    private String hora;
    private String nombreActividadRecurrente;
    private String descripcionActividadRecurrente;

    public HorarioRecurrente(String dia, String hora, String nombreActividadRecurrente, String descripcionActividadRecurrente) {
        this.dia = dia;
        this.hora = hora;
        this.nombreActividadRecurrente = nombreActividadRecurrente;
        this.descripcionActividadRecurrente = descripcionActividadRecurrente;
    }
    
    
    
}
